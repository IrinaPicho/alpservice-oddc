-- Альпсервис — ОДДС: обновление базы данных №3
-- Добавляет "снимок" юрлица и заказчика проекта в каждый отчет (по тому же
-- принципу, что уже сделано для project_code) — чтобы если сотрудника потом
-- переведут в другой проект или другое юрлицо, старые, уже отправленные
-- отчеты не "переписывались" задним числом в выгрузках и в АО-1: они навсегда
-- останутся с тем юрлицом и тем заказчиком, какие были на момент отправки.
-- Выполнить один раз в окне запроса базы данных на Railway (так же, как
-- schema.sql, update-1.sql и update-2.sql). Можно выполнять по одной строке,
-- если разом не сработает.

ALTER TABLE reports ADD COLUMN IF NOT EXISTS legal_entity text;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS project_customer text;

-- Для уже существующих отчетов заполняем снимок текущими данными сотрудника
-- (на момент выполнения этого обновления) — дальше новые отчеты будут
-- получать свой снимок автоматически при отправке.
UPDATE reports r SET legal_entity = u.legal_entity, project_customer = u.project_customer
FROM users u WHERE u.id = r.employee_id AND r.legal_entity IS NULL;
